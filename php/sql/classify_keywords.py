def classify(title: str) -> str:
    """根据标题匹配关键词大类，返回大类名；匹配不到返回'待分类'"""
    title = title.strip()
    for category, keywords in CATEGORIES:
        for kw in keywords:
            if kw in title:
                return category
    return '待分类'


def main():
    # 从stdin读title列表（每行一个）
    results = {}
    for line in sys.stdin:
        title = line.strip()
        if not title:
            continue
        cat = classify(title)
        results[title] = cat

    # 统计
    from collections import Counter
    cnt = Counter(results.values())
    print('=== 分类统计 ===', file=sys.stderr)
    for cat, n in cnt.most_common():
        print(f'  {cat}: {n}', file=sys.stderr)

    # 输出 title<TAB>keyword 到 stdout
    for title, cat in results.items():
        print(f'{title}\t{cat}')


if __name__ == '__main__':
    main()
